# 1. Inicia con un inventario de X pares de zapatos (ingresado por el usuario)
# El valor ingresado se convierte a entero con int() y se asigna a 'inventario'
# En Programación Orientada a Objetos (POO), esto equivaldría a inicializar un atributo de instancia '_inventario' dentro del método constructor __init__ de una clase 'Tienda'.
inventario = int(input("Ingrese la cantidad inicial de pares de zapatos en la tienda: "))

# Variable para contar el número total de transacciones (ventas individuales)
# En POO, esta variable sería otro atributo de instancia (ej. self.transacciones = 0) que rastrea el estado de las operaciones de nuestro objeto.
transacciones = 0

# 2, 3 y 4. Repite el proceso mientras el inventario sea mayor a 0
# Este bucle controla el flujo del programa. En un diseño de clases, esto representaría un método principal o un ciclo de vida que mantiene activo el objeto 'Tienda' mientras su estado 'inventario' sea positivo.
while inventario > 0:
    # Imprime el estado actual del inventario.
    # En POO, esto es equivalente a consultar o leer el valor de un atributo de la instancia actual.
    print(f"\nInventario actual: {inventario} pares de zapatos.")

    # Pregunta cuántos pares se vendieron mediante una entrada de usuario.
    # En una clase, esto equivaldría a recibir un parámetro dentro de un método de venta, por ejemplo: tienda.registrar_venta(vendidos)
    vendidos = int(input("¿Cuántos pares de zapatos se vendieron? "))

    # Validación para no vender más del inventario disponible.
    # En POO, esto representa la lógica de negocio y encapsulamiento: el objeto valida que el parámetro recibido no cause un estado inconsistente o imposible (inventario negativo).
    if vendidos > inventario:
        # Si la validación falla, se muestra un mensaje de error y no se altera el estado del objeto.
        print(f"¡Error! No puedes vender {vendidos} pares porque solo quedan {inventario}.")
        # 'continue' interrumpe la iteración actual y regresa al inicio del bucle sin modificar las variables.
        continue
    # Validación para evitar valores de venta inválidos (cero o negativos).
    elif vendidos <= 0:
        print("Por favor, ingrese un número mayor a 0.")
        # Al igual que antes, 'continue' evita que se procese esta transacción errónea.
        continue

    # Deduce la cantidad vendida del inventario.
    # En POO, esto es una mutación directa del estado del objeto (modificar el valor de self.inventario tras una operación exitosa).
    inventario -= vendidos

    # Incrementa el contador de transacciones.
    # En una clase, esto representa la actualización de otro de los atributos internos que lleva el registro de actividades.
    transacciones += 1

# 5. Imprime el número total de transacciones realizadas al finalizar el ciclo.
# Esto es similar a invocar un método final de reporte de nuestra clase (ej. tienda.generar_reporte_final()) una vez que se cumple la condición de término.
print("\n-------------------------------------------")
print("¡El inventario ha llegado a cero!")
print(f"Número total de transacciones (ventas) realizadas: {transacciones}")