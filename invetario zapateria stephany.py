# Pedimos al usuario la cantidad inicial de pares de zapatos
inventario = int(input("¿Cuántos pares de zapatos tienes? "))


# Creamos una variable para contar cuántas ventas se realizan
transacciones = 0


# Mientras todavía queden zapatos en el inventario,
# el programa seguirá preguntando por las ventas
while inventario > 0:

    # Preguntamos al usuario cuántos pares de zapatos se vendieron
    vendidos = int(input("¿Cuántos pares de zapatos se vendieron? "))


    # Comprobamos si la cantidad vendida es menor
    # o igual a la cantidad disponible
    if vendidos <= inventario:

        # Restamos los zapatos vendidos del inventario
        inventario = inventario - vendidos


        # Aumentamos en 1 el número de transacciones
        transacciones = transacciones + 1


        # Mostramos cuántos pares quedan en la tienda
        print("Inventario restante:", inventario)


    # Si se intentan vender más zapatos de los disponibles
    else:

        # Mostramos un mensaje de error
        print("No puedes vender más zapatos de los que tienes.")


# Cuando el inventario llega a 0,
# el while deja de repetirse


# Avisamos de que ya no quedan zapatos
print("El inventario se ha agotado.")


# Mostramos cuántas ventas se realizaron
print("Número total de transacciones:", transacciones)